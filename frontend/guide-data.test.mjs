import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const durationSource = ts.transpileModule(readFileSync(new URL('./src/mediaDuration.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const durationUrl = 'data:text/javascript;base64,' + Buffer.from(durationSource).toString('base64');
const source = ts.transpileModule(readFileSync(new URL('./src/guideData.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace("'./mediaDuration'", JSON.stringify(durationUrl));
const { mapGuide, shiftDay, londonClock, sortChannels, weekStart } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
assert.deepEqual(londonClock(new Date('2026-09-27T23:30:00Z')), {date:'2026-09-28', now:0.5});
assert.deepEqual(londonClock(new Date('2026-12-27T23:30:00Z')), {date:'2026-12-27', now:23.5});
assert.equal(shiftDay('2026-10-25', 1), '2026-10-26');
assert.equal(shiftDay('2026-03-29', -1), '2026-03-28');
const base = {id:'abcdefghijk', channel:'one', date:'2026-09-27',time:'23:59',title:'Late upload', state:'published',duration:'1:02:03', downloaded:true};
const response = {channels:[{id:'one',name:'Same name',favourite:true},{id:'two',name:'Same name'}], uploads:[base,{...base,id:'scheduled01',state:'scheduled'}, {...base,id:'livevideo01',state:'live'}, {...base,date:'2026-09-26'}, {...base,time:'24:00'}],forecasts:[{...base,id:'expected-id',state:'expected'}],truncated:false};
const channels = mapGuide(response, '2026-09-27');
assert.equal(channels[0].programmes.length, 4);
assert.equal(channels[1].programmes.length, 0);
assert.equal(channels[0].programmes[0].duration, 62.1);
assert.equal(channels[0].programmes[0].durationSeconds,3723,'display retains exact seconds instead of rounding decimal minutes');
for(const [duration,seconds]of [['0:47',47],['10:54',654],['PT2M3S',123]])assert.equal(mapGuide({...response,uploads:[{...base,duration}],forecasts:[]},'2026-09-27')[0].programmes[0].durationSeconds,seconds);
assert.equal(channels[0].programmes[0].note, 'Downloaded');
assert.deepEqual(channels[0].programmes.map(p=>p.status), ['Uploaded','Scheduled','Live now','Expected']);
assert.equal(channels[0].programmes[3].videoId, undefined);
assert.equal(channels[0].programmes[0].videoId, 'abcdefghijk');
assert.equal(channels[1].subscribers,'Not available');
console.log('Guide checks passed: London dates, DST, day navigation, statuses, duration, forecasts and channel identity.');

const ranked=[{id:'a',name:'Alpha',subscriberCount:12,sortMetrics:{latest:50,upcoming:null,activity:2}}, {id:'b',name:'Beta',subscriberCount:40,sortMetrics:{latest:100,upcoming:200,activity:9}}, {id:'c',name:'Unknown'}];
assert.deepEqual(sortChannels(ranked,'latest',false,[]).map(c=>c.id),['b','a','c']);
assert.deepEqual(sortChannels(ranked,'upcoming',false,[]).map(c=>c.id),['b','a','c']);
assert.deepEqual(sortChannels(ranked,'subscribers-asc',false,[]).map(c=>c.id),['a','b','c']);
assert.deepEqual(sortChannels(ranked,'latest',true,['a']).map(c=>c.id),['a','b','c']);
assert.deepEqual(sortChannels(ranked,'favourites',false,['b']).map(c=>c.id),['b']);

assert.equal(weekStart('2026-09-27'),'2026-09-21');
assert.equal(weekStart('2026-09-28'),'2026-09-28');
assert.equal(weekStart('2027-01-01'),'2026-12-28');
const week=mapGuide({...response,uploads:[base,{...base,id:'nextday0001',date:'2026-09-28'},{...base,id:'firstday001',date:'2026-09-21'}],forecasts:[]},'2026-09-21','2026-09-27');
assert.deepEqual(week[0].programmes.map(p=>p.date),['2026-09-21','2026-09-27']);
assert.equal(shiftDay(weekStart('2026-10-25'),6),'2026-10-25');
console.log('Weekly Guide: Monday start, year and DST boundaries, daily grouping and range filtering passed.');
